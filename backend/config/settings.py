# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

database_url = os.getenv('DATABASE_URL', '').strip()

if not database_url:
    raise RuntimeError(
        'DATABASE_URL is required. Set it to your Supabase Postgres connection string in backend/.env.'
    )

try:
    parsed_database_url = urlparse(database_url)
except ValueError as exc:
    raise RuntimeError(
        'DATABASE_URL is malformed. Use the Supabase Postgres connection string from Dashboard → Settings → Database, '\
        'and URL-encode the password if it contains special characters. Example: '\
        'postgresql://postgres:YOUR_PASSWORD@db.<project-ref>.supabase.co:5432/postgres?sslmode=require'
    ) from exc

if parsed_database_url.scheme not in {'postgres', 'postgresql'}:
    raise RuntimeError('DATABASE_URL must use the postgresql:// scheme.')

query_params = parse_qs(parsed_database_url.query)
database_sslmode = query_params.get('sslmode', ['require'])[0]

DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': parsed_database_url.path.lstrip('/') or 'postgres',
        'USER': unquote(parsed_database_url.username or ''),
        'PASSWORD': unquote(parsed_database_url.password or ''),
        'HOST': parsed_database_url.hostname or '',
        'PORT': str(parsed_database_url.port or 5432),
        'OPTIONS': {
            'sslmode': database_sslmode,
        },
    }
}

